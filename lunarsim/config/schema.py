    """Sun geometry: ``manual`` (azimuth/elevation) or ``astronomical`` (site + UTC)."""

    mode: Literal["manual", "astronomical"] = "manual"
    azimuth_deg: float = Field(135.0, ge=0.0, lt=360.0)
