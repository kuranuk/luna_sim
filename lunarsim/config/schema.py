"""Pydantic v2 configuration schema.

Conventions:
* All lengths in metres, angles in radians unless the field name ends in ``_deg``.
* Models are frozen and reject unknown keys (typos fail loudly).
* Default values that are *sample values* (not taken from a specific reference)
  are marked as such; physically sourced defaults cite their reference.
"""

from __future__ import annotations

import hashlib
import json
from typing import Annotated

from pydantic import BaseModel, ConfigDict, Field, model_validator

__all__ = [
    "FractalConfig",
    "TerrainConfig",
    "TiltConfig",
    "WorldConfig",
    "config_hash",
]

PositiveFloat = Annotated[float, Field(gt=0.0)]


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class FractalConfig(_Model):
    """Self-affine fractal base terrain generated by spectral synthesis.

    The isotropic power spectral density is ``P(k) ∝ k^-beta`` with
    ``beta = 2 H + 2`` for a 2-D self-affine surface of Hurst exponent ``H``.
    The amplitude is fixed by the RMS slope at a reference baseline ``L``::

        s(L) = sqrt(<(z(x + L) - z(x))^2>) / L,   rms_slope_deg = atan(s(L))

    (the "RMS deviation / baseline" slope used for LOLA roughness studies).
    """

    enabled: bool = True
    # Sample value. TODO(ref): Rosenburg et al. (2011, JGR 116, E02001) report
    # Hurst exponents of lunar topography by terrain type; confirm a representative value.
    hurst: float = Field(0.9, gt=0.0, lt=1.0)
    # Sample value. TODO(ref): typical RMS slopes per terrain type at a given
    # baseline from Rosenburg et al. (2011) / Kreslavsky et al. (2013).
    rms_slope_deg: float = Field(5.0, ge=0.0, lt=60.0)
    baseline_m: PositiveFloat = 1.0
    # Wavelength [m] above which the spectrum is flattened (None = pure power law
    # down to the grid size). Prevents the largest scales from dominating.
    rolloff_wavelength_m: PositiveFloat | None = None
    # The field is synthesised on a grid `pad_factor` times larger and cropped,
    # so that the output is not periodic (no wrap-around seams).
    pad_factor: float = Field(1.25, ge=1.0, le=4.0)


class TiltConfig(_Model):
    """Regional planar slope added to the terrain (e.g. a south-polar massif flank)."""

    slope_deg: float = Field(0.0, ge=0.0, lt=45.0)
    # Direction of steepest *descent*, azimuth from North clockwise.
    downhill_azimuth_deg: float = Field(0.0, ge=0.0, lt=360.0)


class TerrainConfig(_Model):
    """Regular-grid heightmap (DEM) definition."""

    size_x_m: PositiveFloat = 200.0
    size_y_m: PositiveFloat = 200.0
    resolution_m: PositiveFloat = 0.25
    base_elevation_m: float = 0.0
    # Memory guard: refuse grids larger than this many cells (float64: 8 B/cell
    # for the heightmap alone, several times that during synthesis).
    max_cells: int = Field(64_000_000, gt=0)
    fractal: FractalConfig = FractalConfig()
    tilt: TiltConfig = TiltConfig()

    @property
    def shape(self) -> tuple[int, int]:
        """Grid shape ``(ny, nx)``; cell centres span ``size`` with spacing ``resolution``."""
        nx = round(self.size_x_m / self.resolution_m) + 1
        ny = round(self.size_y_m / self.resolution_m) + 1
        return ny, nx

    @model_validator(mode="after")
    def _check(self) -> TerrainConfig:
        ny, nx = self.shape
        if nx < 8 or ny < 8:
            raise ValueError("terrain must be at least 8 cells in each direction")
        if nx * ny > self.max_cells:
            raise ValueError(
                f"terrain grid {ny}x{nx} = {nx * ny} cells exceeds max_cells={self.max_cells}"
            )
        if self.fractal.enabled:
            if self.fractal.baseline_m < self.resolution_m:
                raise ValueError("fractal.baseline_m must be >= resolution_m")
            if self.fractal.baseline_m > 0.5 * min(self.size_x_m, self.size_y_m):
                raise ValueError("fractal.baseline_m must be <= half the terrain size")
        return self


class WorldConfig(_Model):
    """Top-level scenario configuration. ``seed`` + this config rebuild the world exactly."""

    name: str = "unnamed"
    seed: int = Field(0, ge=0)
    terrain: TerrainConfig = TerrainConfig()


def config_hash(cfg: BaseModel) -> str:
    """SHA-256 of the canonical JSON form of a config (stable across runs)."""
    payload = json.dumps(cfg.model_dump(mode="json"), sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()
