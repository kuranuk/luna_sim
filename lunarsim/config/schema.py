class RockConfig(_Model):
    """Rocks added to the heightmap (half-ellipsoids).

    Size distribution: cumulative fractional area covered by rocks of diameter >= D,
    ``F_k(D) = k exp(-q(k) D)`` with ``q(k) = 1.79 + 0.152 / k`` (D in m;
    Golombek & Rapp 1997, as stated in Golombek et al. 2003). Derived from Mars
    landing sites and Earth analogues; an exponential model of the same form was
    fitted to lunar sites by Li & Wu (2018, JGR Planets 123, doi:10.1029/2017JE005496).
    TODO(ref): lunar-specific k (and q) values.
    """

    enabled: bool = False
    k: float = Field(0.02, gt=0.0, lt=1.0)  # sample value
    d_min_m: PositiveFloat = 0.5
    d_max_m: PositiveFloat = 5.0
    # Visible height / diameter. Sample value. TODO(ref): lunar boulder shape statistics.
    height_ratio: float = Field(0.5, gt=0.0, le=1.5)
    # Footprint minor/major axis ratio ~ Uniform(min, 1).
    axis_ratio_min: float = Field(0.6, gt=0.0, le=1.0)
    ejecta: EjectaRockConfig = EjectaRockConfig()

    @model_validator(mode="after")
    def _check(self) -> RockConfig:
        if self.d_max_m <= self.d_min_m:
            raise ValueError("rocks.d_max_m must be > d_min_m")
        if self.ejecta.outer_radii <= self.ejecta.inner_radii:
            raise ValueError("rocks.ejecta.outer_radii must be > inner_radii")
        return self


class NearPatchConfig(_Model):
    """Fine-resolution patch embedded in the coarse terrain (two-layer terrain, Q3).

    The patch is aligned to a global lattice of tiles (``tile_cells`` cells at
    ``resolution_m``) so it can be regenerated identically around any centre:
    fine fractal detail, small craters and rocks are generated per tile from
    tile-indexed random streams.
    """

    enabled: bool = False
    size_m: PositiveFloat = 100.0
    resolution_m: PositiveFloat = 0.05
    center_x_m: float = 0.0
    center_y_m: float = 0.0
    tile_cells: int = Field(512, ge=64, le=4096)
    overlap_cells: int = Field(64, ge=4, le=1024)
    max_cells: int = Field(64_000_000, gt=0)

    @property
    def shape(self) -> tuple[int, int]:
        """Patch grid shape ``(n, n)``."""
        n = round(self.size_m / self.resolution_m) + 1
        return n, n

    @model_validator(mode="after")
    def _check(self) -> NearPatchConfig:
        n = self.shape[0]
        if n * n > self.max_cells:
            raise ValueError(f"near patch {n}x{n} exceeds max_cells={self.max_cells}")
        if 2 * self.overlap_cells >= self.tile_cells:
            raise ValueError("near.overlap_cells must be < tile_cells / 2")
        return self


class DemConfig(_Model):
    """Real DEM as the large-scale base terrain (SPEC 3.1; optional ``tifffile`` for GeoTIFF).

    The DEM is resampled (cubic spline) onto the world grid; wavelengths longer than
    ``2 x`` the DEM pixel come from the DEM, the fractal continues the power law below
    that (the fractal spectrum is high-passed at the DEM Nyquist frequency), then
    craters and rocks are added as usual.

    Georeferencing (``projection``):

    * ``polar_stereographic``: map metres of a polar stereographic projection on the
      sphere of radius ``radius_m`` (true scale at the pole, central meridian 0°;
      x = ρ sin λ, y = ∓ρ cos λ as used by LOLA polar products). The world origin is
      the site (``site.latitude_deg/longitude_deg``); world axes are true East/North.
    * ``equirectangular``: map units are degrees (x = east longitude, y = latitude);
      also centred on the site.
    * ``local``: map metres used directly as East/North; ``center_x_m/center_y_m``
      give the map point placed at the world origin.

    Heights: ``value * height_scale + height_offset_m`` relative to the reference sphere
    (LOLA). The DEM height at the world origin is subtracted (so z ≈ 0 at the origin;
    ``terrain.base_elevation_m`` is added afterwards). For GeoTIFF the pixel size and
    origin come from the ModelPixelScale / ModelTiepoint tags; for ``.npy`` they must be
    given here (``pixel_size``, ``origin_x``, ``origin_y`` of pixel [0, 0]'s centre,
    rows running towards decreasing y as in GeoTIFF unless ``rows_north_up`` is false).
    """

    enabled: bool = False
    path: str = ""
    projection: Literal["polar_stereographic", "equirectangular", "local"] = "local"
    radius_m: PositiveFloat = 1737.4e3  # IAU mean lunar radius (LOLA reference sphere)
    height_scale: float = 1.0
    height_offset_m: float = 0.0
    nodata: float | None = None  # in addition to the GDAL_NODATA tag; filled by nearest
    center_x_m: float = 0.0  # projection "local" only
    center_y_m: float = 0.0
    pixel_size: PositiveFloat | None = None  # .npy only (map units)
    origin_x: float | None = None
    origin_y: float | None = None
    rows_north_up: bool = True

    @model_validator(mode="after")
    def _check(self) -> DemConfig:
        if self.enabled and not self.path:
            raise ValueError("terrain.dem.path is required when the DEM is enabled")
        return self


class TerrainConfig(_Model):
    """Regular-grid heightmap (DEM) definition."""

    size_x_m: PositiveFloat = 200.0
    size_y_m: PositiveFloat = 200.0
    resolution_m: PositiveFloat = 0.25
    base_elevation_m: float = 0.0
    # Memory guard: refuse grids larger than this many cells (float64: 8 B/cell
    # for the heightmap alone, several times that during synthesis).
    max_cells: int = Field(64_000_000, gt=0)
    fractal: FractalConfig = FractalConfig()
    tilt: TiltConfig = TiltConfig()
    craters: CraterConfig = CraterConfig()
    rocks: RockConfig = RockConfig()
    near: NearPatchConfig = NearPatchConfig()
    dem: DemConfig = DemConfig()
    # Lunar curvature: the tangent-plane world drops by (x² + y²) / (2 R) [m] (≈ 0.29 m at
    # 1 km, 1.15 m at 2 km). Lighting then uses the local vertical at each surface point.
    curvature: bool = False
    moon_radius_m: PositiveFloat = 1737.4e3  # IAU mean radius

    @property
    def finest_resolution_m(self) -> float:
        """Resolution of the finest layer [m]."""
        return self.near.resolution_m if self.near.enabled else self.resolution_m

    @property
    def shape(self) -> tuple[int, int]:
        """Grid shape ``(ny, nx)``; cell centres span ``size`` with spacing ``resolution``."""
        nx = round(self.size_x_m / self.resolution_m) + 1
        ny = round(self.size_y_m / self.resolution_m) + 1
        return ny, nx

    @model_validator(mode="after")
    def _check(self) -> TerrainConfig:
        ny, nx = self.shape
        if nx < 8 or ny < 8:
            raise ValueError("terrain must be at least 8 cells in each direction")
        if nx * ny > self.max_cells:
            raise ValueError(
                f"terrain grid {ny}x{nx} = {nx * ny} cells exceeds max_cells={self.max_cells}"
            )
        if self.fractal.enabled:
            if self.fractal.baseline_m < self.resolution_m:
                raise ValueError("fractal.baseline_m must be >= resolution_m")
            if self.fractal.baseline_m > 0.5 * min(self.size_x_m, self.size_y_m):
                raise ValueError("fractal.baseline_m must be <= half the terrain size")
        fine = self.finest_resolution_m
        if self.craters.enabled and self.craters.sfd.d_min_m < 2.0 * fine:
            raise ValueError("craters.sfd.d_min_m must be >= 2 x finest resolution (unresolvable)")
        if self.rocks.enabled and self.rocks.d_min_m < 2.0 * fine:
            raise ValueError("rocks.d_min_m must be >= 2 x finest resolution (unresolvable)")
        if self.near.enabled:
            nr = self.near
            if nr.resolution_m >= self.resolution_m:
                raise ValueError("near.resolution_m must be finer than terrain.resolution_m")
            if nr.tile_cells * nr.resolution_m < 8.0 * self.resolution_m:
                raise ValueError("near tiles must span >= 8 coarse cells (tile_cells * res)")
            half = 0.5 * nr.size_m + nr.overlap_cells * nr.resolution_m + 2 * self.resolution_m
            if (
                abs(nr.center_x_m) + half > 0.5 * self.size_x_m
                or abs(nr.center_y_m) + half > 0.5 * self.size_y_m
            ):
                raise ValueError("near patch must lie inside the coarse terrain (with margin)")
        return self


