#!/usr/bin/env bash
# Resolve requirements*.in in throw-away venvs and write fully pinned lock files.
# Needs network access (run on a connected machine, then ship the wheelhouse).
set -euo pipefail
cd "$(dirname "$0")/.."
PY="${PYTHON:-python3}"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
for name in requirements requirements-dev; do
  "$PY" -m venv "$tmp/$name"
  "$tmp/$name/bin/pip" install -q --upgrade pip
  "$tmp/$name/bin/pip" install -q -r "$name.in"
  {
    echo "# Generated by scripts/update_lock.sh from $name.in with $("$tmp/$name/bin/python" -V)"
    echo "# Valid for CPython 3.10-3.13 on Linux x86_64 / Windows amd64 (see requirements.in)."
    "$tmp/$name/bin/pip" freeze --exclude-editable | grep -viE '^(pip|lunarsim)=='
  } > "$name.lock"
  echo "wrote $name.lock"
done
