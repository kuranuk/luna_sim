"""Generate LICENSES.md from the current environment with pip-licenses and flag copyleft.

Usage: python scripts/gen_licenses.py   (exit code 1 if a GPL/AGPL/LGPL package is found)
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COPYLEFT = ("GPL", "AGPL", "LGPL", "GNU General Public", "GNU Lesser", "GNU Affero")


def _norm(name: str) -> str:
    return name.lower().replace("_", "-")


def _runtime_packages() -> set[str]:
    """Package names pinned in requirements.lock (everything else is dev-only)."""
    names = set()
    for line in (ROOT / "requirements.lock").read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            names.add(_norm(line.split("==")[0]))
    return names


def main() -> int:
    out = subprocess.run(
        [
            sys.executable,
            "-m",
            "piplicenses",
            "--format=json",
            "--with-urls",
            "--ignore-packages",
            "lunarsim",
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    rows = sorted(json.loads(out.stdout), key=lambda r: r["Name"].lower())
    lines = [
        "# Third-party licenses",
        "",
        "Generated by `python scripts/gen_licenses.py` (pip-licenses). Do not edit by hand.",
        "",
        "| Package | Version | License | Scope | URL |",
        "|---|---|---|---|---|",
    ]
    runtime = _runtime_packages()
    bad = []
    for r in rows:
        scope = "runtime" if _norm(r["Name"]) in runtime else "dev"
        lic = r["License"].replace("|", "/").replace("\n", " ")
        if len(lic) > 80:
            lic = lic[:77] + "..."
        lines.append(f"| {r['Name']} | {r['Version']} | {lic} | {scope} | {r['URL']} |")
        if scope == "runtime" and any(c in r["License"] for c in COPYLEFT):
            bad.append(f"{r['Name']} ({r['License']})")
    (ROOT / "LICENSES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote LICENSES.md ({len(rows)} packages)")
    if bad:
        print("copyleft runtime dependencies found:", ", ".join(bad), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
